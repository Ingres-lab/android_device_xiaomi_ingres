"""
Haptic waveform synthesizer for the AW86927 "custom wave" (RTP streaming) mode.
Output: raw signed 8-bit samples at FS Hz, one file per effect.

Design, after Apple's Core Haptics model:
  * transient  = 0.5..3 cycles of the actuator resonance (F0) under an envelope; intensity scales the
                 amplitude, "sharpness" is the attack time and the amount of braking;
  * brake      = a short opposing-phase burst after the main pulse, so the mass stops at once
                 and the tap feels crisp instead of ringing;
  * continuous = sine at F0 with an amplitude ramp.
"""
import math, os, sys

FS = 24000
F0 = float(os.environ.get("NEO_F0", "129.0"))   # Hz; the driver reports f0=1290 (0.1 Hz units)
OUT = sys.argv[1] if len(sys.argv) > 1 else "waves"

def burst(cycles, amp, attack=0.5, phase=0.0, freq=None):
    """One shaped burst: raised-cosine envelope with the peak at `attack` (0..1) of its length."""
    f = freq or F0
    n = max(8, int(round(cycles * FS / f)))
    out = []
    pk = max(1e-3, min(0.999, attack))
    for i in range(n):
        t = i / (n - 1)
        env = 0.5 - 0.5 * math.cos(math.pi * t / pk) if t < pk else 0.5 + 0.5 * math.cos(math.pi * (t - pk) / (1 - pk))
        out.append(amp * env * math.sin(2 * math.pi * f * i / FS + phase))
    return out

def silence(ms):
    return [0.0] * int(FS * ms / 1000)

def transient(cycles, amp, attack=0.35, brake=0.5, brake_cycles=0.6):
    w = burst(cycles, amp, attack)
    if brake > 0:
        # opposing phase to the motor's motion at the end of the pulse
        w += burst(brake_cycles, amp * brake, 0.4, phase=math.pi)
    return w

def ramp(ms, a0, a1):
    n = int(FS * ms / 1000)
    return [(a0 + (a1 - a0) * i / (n - 1)) * math.sin(2 * math.pi * F0 * i / FS) for i in range(n)]

def seq(*parts):
    out = []
    for p in parts: out += p
    return out

E = {}
# --- Apple UIFeedbackGenerator-style set -------------------------------------------------------
E["selection"]        = transient(1.0, 0.40, 0.30, 0.45)
E["impact_light"]     = transient(1.0, 0.55, 0.30, 0.45)
E["impact_medium"]    = transient(1.5, 0.75, 0.30, 0.50)
E["impact_heavy"]     = transient(2.0, 1.00, 0.18, 0.60, 1.0)
E["impact_soft"]      = transient(3.0, 0.70, 0.50, 0.0)                       # rounded, no brake: a cushion
E["impact_rigid"]     = transient(0.75, 0.90, 0.20, 0.70, 0.75)               # hard, short, damped
E["notification_success"] = seq(transient(1.0, 0.45, 0.3, 0.45), silence(80), transient(1.5, 0.80, 0.3, 0.5))
E["notification_warning"] = seq(transient(1.5, 0.70, 0.25, 0.5), silence(110), transient(1.5, 0.95, 0.25, 0.5))
E["notification_error"]   = seq(transient(1.0, 0.65, 0.25, 0.5), silence(55), transient(1.0, 0.65, 0.25, 0.5),
                               silence(55), transient(1.5, 1.00, 0.25, 0.55))
E["keyboard_click"]   = transient(0.75, 0.28, 0.25, 0.40, 0.5)
E["scroll_detent"]    = transient(0.6, 0.22, 0.25, 0.35, 0.5)
# --- extras --------------------------------------------------------------------------------------
E["long_press_swell"] = seq(ramp(140, 0.05, 0.75), transient(0.75, 0.9, 0.2, 0.7, 0.75))
E["heartbeat"]        = seq(transient(1.5, 0.90, 0.25, 0.5), silence(110), transient(1.5, 0.65, 0.3, 0.5))
E["tick_double"]      = seq(transient(0.75, 0.50, 0.25, 0.4, 0.5), silence(45), transient(0.75, 0.50, 0.25, 0.4, 0.5))

# --- Android CompositePrimitive set (vibrator HAL) ------------------------------------------------
P = {}
P["CLICK"]       = E["impact_medium"]
P["THUD"]        = E["impact_heavy"]
P["SPIN"]        = seq(ramp(32, 0.10, 0.80), ramp(32, 0.80, 0.10))
P["QUICK_RISE"]  = seq(ramp(36, 0.05, 0.90), transient(0.5, 0.45, 0.2, 0.5, 0.5))
P["SLOW_RISE"]   = seq(ramp(150, 0.05, 0.85), transient(0.5, 0.40, 0.2, 0.5, 0.5))
P["QUICK_FALL"]  = seq(ramp(36, 0.90, 0.05))
P["LIGHT_TICK"]  = E["selection"]
P["LOW_TICK"]    = [x for x in burst(1.0, 0.55, 0.3, freq=F0 * 0.75)] + burst(0.6, 0.22, 0.4, phase=math.pi, freq=F0 * 0.75)

HEADER = None
if "--header" in sys.argv:
    HEADER = sys.argv[sys.argv.index("--header") + 1]
    sys.argv = [a for a in sys.argv if a not in ("--header", HEADER)]
    OUT = sys.argv[1] if len(sys.argv) > 1 else OUT

os.makedirs(OUT, exist_ok=True)
for name, w in E.items():
    pk = max(abs(x) for x in w)
    data = bytes(int(round(max(-1.0, min(1.0, x)) * 127)) & 0xFF for x in w)
    with open(os.path.join(OUT, name + ".s8"), "wb") as f:
        f.write(data)
    print("%-22s %4d ms  %5d bytes  peak %.2f" % (name, 1000 * len(w) / FS, len(data), pk))

def q8(w):
    return [int(round(max(-1.0, min(1.0, x)) * 127)) for x in w]

if HEADER:
    with open(HEADER, "w") as h:
        h.write("// Generated by synth.py (F0=%.1f Hz, FS=%d Hz). Do not edit.\n#pragma once\n#include <cstdint>\n#include <cstddef>\n\n" % (F0, FS))
        h.write("namespace neo_haptics {\nconstexpr int kSampleRate = %d;\nconstexpr float kF0Hz = %.1ff;\n" % (FS, F0))
        h.write("struct Wave { const char* name; const int8_t* data; size_t len; };\n")
        names = []
        for group, d in (("fx", E), ("prim", P)):
            for k, w in d.items():
                var = "k_%s_%s" % (group, k)
                data = q8(w)
                h.write("static const int8_t %s[] = {%s};\n" % (var, ",".join(str(v) for v in data)))
                names.append((group, k, var, len(data)))
        for group in ("fx", "prim"):
            h.write("static const Wave k_%s_table[] = {\n" % group)
            for g, k, var, n in names:
                if g == group:
                    h.write('    {"%s", %s, %d},\n' % (k, var, n))
            h.write("};\n")
        h.write("}  // namespace neo_haptics\n")
    print("header written:", HEADER)
